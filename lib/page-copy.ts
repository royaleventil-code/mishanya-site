export function getPageCopy(locale: Locale): PageCopy {
  return PAGE_COPY[locale];
}

export function localizeProofImageAlt(
  locale: Locale,
  type: "gallery" | "review" | "media",
  fallback: string,
): string {
  if (locale === "ru") return fallback;
  return PAGE_COPY.he.gallery.alt[type];
}

export function localizeProofLinkLabel(locale: Locale, fallback: string): string {
  if (locale === "ru") return fallback;
  if (fallback.toLowerCase().includes("facebook")) return PAGE_COPY.he.gallery.linkLabels.facebookReviews;
  if (fallback.toLowerCase().includes("youtube")) return PAGE_COPY.he.gallery.linkLabels.youtubeVideo;
  return fallback;
}

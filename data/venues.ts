export function getVenueById(id: string): Venue | undefined {
  return VENUES.find((venue) => venue.id === id);
}

/** Есть ли заполненная копия площадки для локали (пустой иврит → страница не генерируется) */
export function hasVenueCopy(locale: Locale, id: string): boolean {
  const venue = getVenueById(id);
  if (!venue) return false;
  const copy = venue.copy[locale];
  return Boolean(
    copy && copy.h1.trim() !== "" && copy.intro.length > 0 && copy.faq.length > 0,
  );
}

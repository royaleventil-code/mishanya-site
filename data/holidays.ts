export function getHolidayById(id: string): Holiday | undefined {
  return HOLIDAYS.find((holiday) => holiday.id === id);
}

/** Есть ли у праздника контент на данном языке (he-страницы без перевода не публикуем) */
export function hasHolidayCopy(locale: Locale, id: string): boolean {
  if (locale === "ru") return true;
  const holiday = getHolidayById(id);
  return Boolean(holiday && holiday.copy[locale].h1.trim() !== "");
}

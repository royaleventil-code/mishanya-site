export function getBlogPostBySlug(slug: string): BlogPost | undefined {
  return BLOG_POSTS.find((post) => post.slug === slug);
}

export function hasBlogCopy(locale: Locale, slug: string): boolean {
  const post = getBlogPostBySlug(slug);
  return Boolean(post?.copy[locale]);
}

/** Статьи для списка: свежие сверху */
export function blogPostsForLocale(locale: Locale): BlogPost[] {
  return BLOG_POSTS.filter((post) => post.copy[locale]).sort(
    (a, b) => b.datePublished.localeCompare(a.datePublished) || a.slug.localeCompare(b.slug),
  );
}

export function formatBlogDate(iso: string, locale: Locale): string {
  return new Date(`${iso}T12:00:00Z`).toLocaleDateString(locale === "he" ? "he-IL" : "ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

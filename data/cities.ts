export function getCityById(id: string): City | undefined {
  return CITIES.find((city) => city.id === id);
}

/** Есть ли заполненная копия города для локали (пустой иврит → страница не генерируется) */
export function hasCityCopy(locale: Locale, id: string): boolean {
  const city = getCityById(id);
  if (!city) return false;
  const copy = city.copy[locale];
  return Boolean(
    copy && copy.h1.trim() !== "" && copy.intro.length > 0 && copy.faq.length > 0,
  );
}

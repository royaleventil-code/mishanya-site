/** Внешняя ссылка на просмотр — эмбед у канала мультиков запрещён */
export function cartoonWatchUrl(videoId: string): string {
  return `https://www.youtube.com/watch?v=${videoId}`;
}

/**
 * Формат просмотров под YouTube: усечение (не округление) до 1 знака.
 * RU: «12,5 млн просмотров» / «850 тыс. просмотров».
 * HE: цифры не переводятся, шаблон «אלף/מיליון צפיות».
 */
export function formatCartoonViews(views: number, locale: Locale): string {
  if (views >= 1_000_000) {
    const millions = Math.floor(views / 100_000) / 10;
    return locale === "he"
      ? `${millions} מיליון צפיות`
      : `${String(millions).replace(".", ",")} млн просмотров`;
  }
  const thousands = Math.floor(views / 1000);
  return locale === "he" ? `${thousands} אלף צפיות` : `${thousands} тыс. просмотров`;
}

